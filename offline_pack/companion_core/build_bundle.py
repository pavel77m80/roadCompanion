def main():
    src = json.loads((EXP / "poi_with_sources.json").read_text(encoding="utf-8"))
    route = json.loads((EXP / "route.geojson").read_text(encoding="utf-8"))
    pois = {(p["osm_type"], p["osm_id"]): p for p in src["poi"]}

    missing = [(r[0], r[1]) for r in INCLUDE if (r[0], r[1]) not in pois]
    if missing:
        raise SystemExit(f"Включённые POI отсутствуют в данных: {missing}")

    stories, sources = build_stories(pois)
    stories.sort(key=lambda s: s["route_distance_m"])
    # Перенумерация story_id после сортировки сохраняет порядок st-001..st-012
    for i, s in enumerate(stories, 1):
        parts = s["story_id"].split("-")
        s["story_id"] = f"st-{i:03d}-{'-'.join(parts[2:])}"

    route_props = route["features"][0]["properties"]
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "bundle_id": BUNDLE_ID,
        "bundle_version": "1.0.0",
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "generated_from": {
            "experiment_snapshot": "2026-10-09",
            "poi_with_sources_sha256": hashlib.sha256(
                (EXP / "poi_with_sources.json").read_bytes()).hexdigest()[:16],
            "route_sha256": hashlib.sha256(
                (EXP / "route.geojson").read_bytes()).hexdigest()[:16],
        },
        "route": {
            "file": "route.geojson",
            "distance_m": route_props["distance_m"],
            "duration_s": route_props["duration_s"],
            "n_points": route_props["n_points"],
            "start": route_props["start"], "end": route_props["end"],
        },
        "n_stories": len(stories),
        "language": "ru",
        "corridor_radius_m": 2000,
        "data_provenance": {
            "osm": "© участники OpenStreetMap, ODbL 1.0",
            "wikipedia": "тексты Wikipedia под CC BY-SA; в бандле — собственные пересказы",
            "wikidata": "данные Wikidata под CC0",
        },
        "incomplete_data": sorted({u for s in stories for u in s["uncertainties"]}),
        "selection_summary": {
            "included": len(stories),
            "excluded_documented": len(EXCLUDE),
        },
    }

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT / "stories.json").write_text(
        json.dumps(stories, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT / "sources.json").write_text(
        json.dumps(list(sources.values()), ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT / "route.geojson").write_text(
        json.dumps(route, ensure_ascii=False), encoding="utf-8")

    # Отчёт отбора (вне бандла, для аудита)
    pool = json.loads((ROOT / "offline_pack" / "preflight_report.json")
                      .read_text(encoding="utf-8"))["candidate_pool"]
    inc_keys = {(r[0], r[1]) for r in INCLUDE}
    excl_keys = {(r[0], r[1]) for r in EXCLUDE}

    def parse(poi_str):
        t, i = poi_str.split("/")
        return (t, int(i))

    report = {
        "included": [
            {"poi": f"{k[0]}/{k[1]}", "name": pois[k].get("name"),
             "distance_to_route_m": pois[k]["distance_to_route_m"],
             "along_route_m": pois[k]["along_route_m"], "reason": reason,
             "trigger_radius_m": tr}
            for k, _sid, tr, reason in
            [((row[0], row[1]), row[2], row[3], row[4]) for row in INCLUDE]],
        "excluded": [
            {"poi": f"{row[0]}/{row[1]}", "name": row[2], "reason": row[3]}
            for row in EXCLUDE],
        "pool_size": len(pool),
        "pool_not_selected": [
            {"poi": c["poi"], "name": c["name"],
             "reasons": c.get("reject_reasons", []) or ["не выбран при отборе"]}
            for c in pool if parse(c["poi"]) not in inc_keys
            and parse(c["poi"]) not in excl_keys],
    }
    (ROOT / "offline_pack" / "selection_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")

    sizes = {f.name: f.stat().st_size for f in OUT.iterdir()}
    print(f"Бандл собран: {OUT}")
    print(f"Историй: {len(stories)}; источников: {len(sources)}; файлы: {sizes}")


def _parse(poi_str):
    t, i = poi_str.split("/")
    return (t, int(i))


if __name__ == "__main__":
    main()
