def F(text, kind, *source_ids):
    return {"text": text, "kind": kind, "source_ids": list(source_ids)}


def build_stories(pois):
    S = []
    used_sources = {}

    def reg(src):
        used_sources.setdefault(src["source_id"], src)

    def story(key, sid, title, summary, spoken, facts, uncertainties):
        p = pois[key]
        wd = p["source"].get("wikidata") or {}
        srcs = []
        if wd.get("qid"):
            s = wd_src(wd["qid"], wd.get("label_ru") or p.get("name"))
            reg(s)
            srcs.append(s["source_id"])
        # Wikipedia-источник: приоритет у канонического sitelink из Wikidata,
        # OSM-тег — запасной вариант (названия страниц могут расходиться)
        import urllib.parse
        wp_title = None
        if wd.get("wikipedia_url"):
            lang, tail = wd["wikipedia_url"].split("//", 1)[1].split(".", 1)
            wp_title = (lang, urllib.parse.unquote(tail.split("/wiki/", 1)[-1])
                        .replace("_", " "))
        elif p.get("wikipedia"):
            parts = p["wikipedia"].split(":", 1)
            lang = parts[0] if len(parts) == 2 and len(parts[0]) <= 3 else "ru"
            wp_title = (lang, parts[-1].replace("_", " "))
        if wp_title:
            s = wp_src(*wp_title)
            reg(s)
            srcs.append(s["source_id"])
        s = osm_src(key[0], key[1])
        reg(s)
        srcs.append(s["source_id"])
        spoken = " ".join(spoken.split())
        words = len(spoken.split())
        duration = min(90, max(15, int(round(words / 2.0 / 5.0)) * 5))
        # Радиус триггера не может быть меньше фактического расстояния POI от
        # дороги, иначе история недостижима: радиус >= дистанция + запас 75 м.
        manual = dict(((row[0], row[1]), row[3]) for row in INCLUDE)[key]
        radius = max(manual, int(math.ceil((p["distance_to_route_m"] + 75) / 25.0) * 25))
        S.append({
            "story_id": f"st-{len(S)+1:03d}-{sid}",
            "poi_id": f"{key[0]}/{key[1]}",
            "title": title,
            "short_summary": summary,
            "spoken_text": spoken,
            "estimated_duration_seconds": duration,
            "coordinates": {"lat": p["lat"], "lon": p["lon"]},
            "route_distance_m": p["along_route_m"],
            "trigger_radius_m": radius,
            "facts": facts,
            "sources": srcs,
            "uncertainties": uncertainties,
            "content_language": "ru",
            "content_version": SCHEMA_VERSION,
        })

