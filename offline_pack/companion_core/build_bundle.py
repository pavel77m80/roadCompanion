def wd_src(qid, label):
    return {"source_id": f"wikidata:{qid}", "type": "wikidata-entity",
            "title": label or qid, "authors": "участники Wikidata",
            "license": "CC0 1.0", "license_url": "https://creativecommons.org/publicdomain/zero/1.0/",
            "url": f"https://www.wikidata.org/wiki/{qid}"}


def wp_src(lang, title):
    page = title.replace(" ", "_")
    return {"source_id": f"wikipedia:{lang}:{title}", "type": "wikipedia-article",
            "title": title, "lang": lang,
            "authors": "участники статьи (см. историю правок страницы)",
            "license": "CC BY-SA 4.0",
            "license_url": "https://creativecommons.org/licenses/by-sa/4.0/deed.ru",
            "url": f"https://{lang}.wikipedia.org/wiki/{page}",
            "attribution_note": "Пересказ, не копия текста; указание автора и лицензии "
                                "сохранено по требованию CC BY-SA."}


def osm_src(osm_type, osm_id):
    return {"source_id": f"osm:{osm_type}/{osm_id}", "type": "openstreetmap-object",
            "title": f"OSM {osm_type}/{osm_id}", "authors": "участники OpenStreetMap",
            "license": "ODbL 1.0",
            "license_url": "https://opendatacommons.org/licenses/odbl/1-0/",
            "url": f"https://www.openstreetmap.org/{osm_type}/{osm_id}"}


